// 외부 기관·법적 대응을 가리키는 말 — 한 곳에서 정의한다.
//
// 왜 모았나:
// 같은 개념을 세 파일이 각자 적어 두고 있었고, 그중 둘이 축약형('방통위')만 알았다.
// 그런데 도메인 사전(domainLexicon)이 보정 단계에서 '방통위'를 '방송통신위원회'로
// 바꾼다. 파이프라인은 보정본을 그대로 하류로 넘기므로, 사전을 통과한 통화에서는
// 그 둘이 아무것도 못 잡았다. 실측:
//
//   "안 고쳐주면 방통위에 신고하겠습니다"
//     원문        → 법무·분쟁 대응팀 P1 · 이탈 위험 20점
//     사전 보정 후 → 네트워크 품질팀 P2 · 이탈 위험 0점
//
// 가장 급한 통화가 조용히 일반 통화로 강등됐다. 사전이 정확해질수록 하류가 더 많이
// 놓치는 구조였다 — 보정은 잘 돌고 있었고, 규칙이 보정 결과를 몰랐던 것이다.
//
// 그래서 사전에 표제어가 늘 때 규칙도 함께 늘도록 어휘를 여기 한 곳에 둔다.
// 정규식이 아니라 **낱말 목록**으로 두는 이유는, 쓰는 쪽마다 필요한 형태가 다르기
// 때문이다(전역 플래그·다른 낱말과의 결합). 목록에서 만들어 쓴다.

// 표제어와 축약형을 함께 적는다. domainLexicon이 어느 방향으로 보정하든 걸리게 하려면
// 양쪽이 다 있어야 한다 — 한쪽만 두면 이번과 같은 일이 반대 방향으로 다시 난다.
export const EXTERNAL_AGENCY_TERMS = [
  '방송통신위원회',
  '방통위',
  '소비자원',
  '소비자보호원',
  '국민신문고',
]

export const LEGAL_ACTION_TERMS = ['소송', '고소', '고발', '법적', '변호사', '손해배상']

export const MEDIA_TERMS = ['언론', '제보', '기사화']

// 셋을 합친 것 — "이 통화는 외부로 나갈 수 있다"는 신호 하나로 쓰는 자리용
// (법무 우선 배정, 이탈 위험 신호).
export const ESCALATION_TERMS = [...EXTERNAL_AGENCY_TERMS, ...LEGAL_ACTION_TERMS, ...MEDIA_TERMS]

// 목록 → 정규식. 낱말에 정규식 메타문자가 없지만, 나중에 누가 '(' 든 표제어를
// 넣어도 조용히 깨지지 않도록 이스케이프한다.
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
export function termsPattern(terms, flags = '') {
  return new RegExp(terms.map(escape).join('|'), flags)
}

// 자주 쓰는 형태를 미리 만들어 둔다 (호출부가 매번 만들지 않게)
export const ESCALATION_RE = termsPattern(ESCALATION_TERMS)
