// 한국어 토큰 추출 — 2글자 이상 어절 단위(조사 등 짧은 어미는 자연히 걸러진다)
function tokens(text) {
  return (text || '')
    .toLowerCase()
    .split(/[^가-힣a-z0-9]+/)
    .filter((t) => t.length >= 2)
}

// 임베딩 폴백용 키워드 랭킹 — 질문 토큰이 문서에 포함될 때마다 토큰 길이만큼 가점.
// (긴 토큰 매치일수록 우연 일치 확률이 낮으므로 가중치를 준다)
export function rankByKeyword(question, docs = FAQ_DOCS) {
  const qTokens = [...new Set(tokens(question))]
  return docs
    .map((doc) => {
      const hay = `${doc.title} ${doc.body}`.toLowerCase()
      let score = 0
      for (const t of qTokens) {
        if (hay.includes(t)) score += t.length
      }
      return { ...doc, score }
    })
    .sort((a, b) => b.score - a.score)
}

// 코사인 유사도 — 서버의 임베딩 검색과 테스트가 공유한다.
export function cosineSim(a, b) {
  let dot = 0
  let na = 0
  let nb = 0
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i]
    na += a[i] * a[i]
    nb += b[i] * b[i]
  }
  if (!na || !nb) return 0
  return dot / (Math.sqrt(na) * Math.sqrt(nb))
}
